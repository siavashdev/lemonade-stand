import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import type { Recipe } from '@shared/types'
import {
  MAX_RECIPE_CHARS,
  parseRecipeMarkdown,
  serializeRecipeMarkdown,
  uniqueRecipeId
} from '@shared/recipes'
import { readSettings, writeSettings } from '../config'

// Recipes live one-folder-per-recipe under `recipes/<id>/SKILL.md` inside the
// app's writable config dir, the same per-user location as conversations. The
// SKILL.md stays portable (name + description frontmatter + body); whether a
// recipe is switched on is app state, kept in settings so the file isn't touched.
const DIR = 'recipes'
const FILE = 'SKILL.md'

function recipesDir(cwd: string): string {
  return resolve(cwd, DIR)
}

// Ids are generated by us, but sanitize anyway so a malformed id can never
// escape the recipes directory via `..` or path separators.
function sanitizeId(id: string): string {
  return id.replace(/[^a-z0-9-]/gi, '').toLowerCase()
}

function recipePath(cwd: string, id: string): string {
  return join(recipesDir(cwd), sanitizeId(id), FILE)
}

/** List saved recipes, sorted by name. Unreadable folders are skipped. */
export function listRecipes(cwd: string): Recipe[] {
  const dir = recipesDir(cwd)
  if (!existsSync(dir)) return []
  const disabled = new Set(readSettings(cwd).disabledRecipes ?? [])
  const recipes: Recipe[] = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    try {
      const raw = readFileSync(join(dir, entry.name, FILE), 'utf8')
      const parsed = parseRecipeMarkdown(raw, entry.name)
      recipes.push({
        id: entry.name,
        name: parsed.name,
        description: parsed.description,
        body: parsed.body,
        enabled: !disabled.has(entry.name)
      })
    } catch {
      // Skip a folder with a missing or unreadable SKILL.md.
    }
  }
  return recipes.sort((a, b) => a.name.localeCompare(b.name))
}

/** Reject content the agent couldn't use or that would crowd out the context. */
function validate(recipe: { name: string; description: string; body: string }): void {
  if (!recipe.name.trim()) throw new Error('A recipe needs a name.')
  if (!recipe.body.trim()) throw new Error('A recipe needs instructions in its body.')
  if (recipe.body.length > MAX_RECIPE_CHARS) {
    throw new Error(
      `This recipe is too long (${recipe.body.length} characters; the limit is ${MAX_RECIPE_CHARS}).`
    )
  }
}

function setEnabled(cwd: string, id: string, enabled: boolean): void {
  const current = readSettings(cwd).disabledRecipes ?? []
  const disabled = new Set(current)
  if (enabled) disabled.delete(id)
  else disabled.add(id)
  if (disabled.size === current.length && current.every((x) => disabled.has(x))) return
  writeSettings(cwd, { disabledRecipes: [...disabled] })
}

/** Create or update a recipe; a new one gets a unique id derived from its name. */
export function saveRecipe(cwd: string, input: Omit<Recipe, 'id'> & { id?: string }): Recipe {
  validate(input)
  const taken = listRecipes(cwd).map((r) => r.id)
  const existing = input.id ? sanitizeId(input.id) : ''
  const id = existing && taken.includes(existing) ? existing : uniqueRecipeId(input.name, taken)
  const recipe: Recipe = {
    id,
    name: input.name.trim().slice(0, 80),
    description: input.description.trim().slice(0, 400),
    body: input.body.trim(),
    enabled: input.enabled
  }
  mkdirSync(join(recipesDir(cwd), id), { recursive: true })
  writeFileSync(recipePath(cwd, id), serializeRecipeMarkdown(recipe), 'utf8')
  setEnabled(cwd, id, recipe.enabled)
  return recipe
}

/** Delete a recipe folder (and forget its enabled flag). */
export function deleteRecipe(cwd: string, id: string): void {
  const safe = sanitizeId(id)
  if (!safe) return
  rmSync(join(recipesDir(cwd), safe), { recursive: true, force: true })
  setEnabled(cwd, safe, true)
}

export function setRecipeEnabled(cwd: string, id: string, enabled: boolean): void {
  if (existsSync(recipePath(cwd, id))) setEnabled(cwd, sanitizeId(id), enabled)
}

/** Import markdown documents as new recipes (never overwriting existing ones).
 * Returns how many were imported and a message per file that couldn't be. */
export function importRecipeFiles(
  cwd: string,
  files: { name: string; content: string }[]
): { imported: number; errors: string[] } {
  let imported = 0
  const errors: string[] = []
  for (const file of files) {
    const fallback = file.name.replace(/\.(md|markdown|txt)$/i, '')
    try {
      const parsed = parseRecipeMarkdown(file.content, fallback)
      saveRecipe(cwd, { ...parsed, enabled: true })
      imported++
    } catch (err) {
      errors.push(`${file.name}: ${err instanceof Error ? err.message : String(err)}`)
    }
  }
  return { imported, errors }
}

/** Look up recipes by id, skipping unknown ones. */
export function getRecipes(cwd: string, ids: string[]): Recipe[] {
  const wanted = new Set(ids)
  return listRecipes(cwd).filter((r) => wanted.has(r.id))
}
